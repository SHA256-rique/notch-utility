import AppKit

/// Clipboard capture.
///
/// ## Why this polls, and why that is still the cheap option
/// macOS has never offered a pasteboard-change notification. Every clipboard
/// manager on the platform polls `NSPasteboard.changeCount`.
///
/// What makes it acceptable is *what* is polled. `changeCount` is a single
/// monotonically-increasing integer maintained by the pasteboard server; reading
/// it is one cheap IPC round trip and, crucially, does **not** deserialise the
/// pasteboard contents. We only touch the actual data on the ticks where the
/// counter moved -- which is a handful of times an hour, not 3,600.
///
/// Contrast with the naive version: calling `pasteboard.string(forType:)` every
/// tick forces the *owning application* to render its data into the requested
/// type on every single poll. Poll a 20MB image on the pasteboard at 1Hz that
/// way and you make some other app do real work 3,600 times an hour.
///
/// ## Why it is exempt from the polling hub
/// The hub switches off when the panel is collapsed -- but clipboard history
/// that only records while you are hovering the notch is useless. So this runs
/// continuously, at a deliberately slow 1.2s, and its cost is measured in the
/// README benchmark as part of the idle figure rather than hidden from it.
/// Turning capture off in Settings stops the source outright.
@MainActor
final class ClipboardWatcher {
    static let shared = ClipboardWatcher()

    private var source: DispatchSourceTimer?
    private var lastChangeCount: Int = NSPasteboard.general.changeCount
    private var suppressUntilChangeCount: Int?

    private init() {}

    func start() {
        stop()
        guard Settings.shared.data.captureClipboard else {
            Log.tier1.info("clipboard capture disabled by user")
            return
        }
        lastChangeCount = NSPasteboard.general.changeCount

        let t = DispatchSource.makeTimerSource(queue: .main)
        // 1.2s with 400ms leeway. Nobody can tell the difference between a
        // clipboard entry appearing in 200ms and in 1.2s, and the leeway lets
        // the kernel fold this wakeup into one it was already doing.
        t.schedule(deadline: .now() + 1.2, repeating: 1.2, leeway: .milliseconds(400))
        t.setEventHandler { [weak self] in self?.check() }
        t.resume()
        source = t
    }

    func stop() {
        source?.cancel()
        source = nil
    }

    /// Called before we write to the pasteboard ourselves, so a snippet the user
    /// just copied out of NotchScotch does not immediately reappear as a new
    /// captured entry.
    func suppressNextChange() {
        suppressUntilChangeCount = NSPasteboard.general.changeCount + 1
    }

    private func check() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }   // the cheap early-out
        lastChangeCount = count

        if let suppress = suppressUntilChangeCount, count <= suppress {
            suppressUntilChangeCount = nil
            return
        }

        // Respect the two conventions apps use to say "do not record this".
        // Password managers and secure fields set `concealed`; short-lived
        // internal drags set `transient`. Honouring these is the difference
        // between a clipboard manager you can trust with a 1Password copy and
        // one you cannot.
        let types = pb.types ?? []
        let isConcealed = types.contains(NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
            || types.contains(NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        let isTransient = types.contains(NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        if (isConcealed && !Settings.shared.data.captureFromPasswordManagers) || isTransient {
            Log.tier1.debug("skipping concealed/transient pasteboard item")
            return
        }

        let app = NSWorkspace.shared.frontmostApplication
        let appName = app?.localizedName ?? ""
        let bundleID = app?.bundleIdentifier ?? ""

        // Files first: a Finder copy carries both file URLs and a string
        // representation, and the URLs are the more useful of the two.
        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            SnippetStore.shared.capture(.files(urls.map(\.path)), appName: appName, bundleID: bundleID)
            return
        }
        if let text = pb.string(forType: .string) {
            SnippetStore.shared.capture(.text(text), appName: appName, bundleID: bundleID)
        }
    }
}
